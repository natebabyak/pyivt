"""Command-line tools for IVT tables."""

import argparse
import re
import unicodedata
from keyword import iskeyword, kwlist
from pathlib import Path
from tempfile import NamedTemporaryFile
from typing import Literal

from pyivt import __version__
from pyivt import open as open_ivt

_RUFF_LINE_LENGTH = 88


def _words(label: str) -> list[str]:
    normalized = unicodedata.normalize("NFKD", label)
    text = "".join(
        character for character in normalized if not unicodedata.combining(character)
    )
    return re.findall(r"[A-Za-z0-9]+", text)


def _unique(name: str, used: set[str], suffix: int) -> str:
    candidate = name
    while candidate in used:
        candidate = f"{name}_{suffix}"
        suffix += 1
    used.add(candidate)
    return candidate


def _write_types(source: Path, output: Path, language: Literal["en", "fr"]) -> None:
    if source.resolve() == output.resolve():
        raise ValueError("the output must differ from the input file")
    ivt = open_ivt(source)
    members = ivt.members(language=language)
    digest, _, _ = ivt._member_fields()
    lines = [
        "# Generated by pyivt. Do not edit by hand.",
        f"# Source SHA-256: {digest}",
        f"# pyivt version: {__version__}",
        f"# Language: {language}",
        "",
        "from enum import IntEnum",
        "from typing import TypedDict",
    ]
    classes = {"Dimensions", "IntEnum", "TypedDict", *kwlist}
    fields = []
    for slug, lookup in members.items():
        class_name = "".join(word.capitalize() for word in _words(slug)) or "Axis"
        if class_name[0].isdigit():
            class_name = f"Axis{class_name}"
        enum_name = _unique(class_name, classes, 2)
        fields.append(f'        "{slug}": {enum_name} | list[{enum_name}],')
        lines.extend(("", "", f"class {enum_name}(IntEnum):"))
        labels = lookup["label"].to_pylist()
        codes = lookup["code"].to_pylist()
        names = []
        for label, code in zip(labels, codes, strict=True):
            name = "_".join(_words(label or "")).upper() or f"CODE_{code}"
            if name[0].isdigit() or iskeyword(name.lower()) or iskeyword(name.title()):
                name = f"_{name}"
            names.append(name)
        reserved = set(names)
        used: set[str] = set()
        for name, code in zip(names, codes, strict=True):
            if name in used:
                name = _unique(f"{name}_{code}", reserved, 2)
            used.add(name)
            prefix = f"    {name} = "
            assignment = f"{prefix}{code}"
            if len(prefix) + 1 <= _RUFF_LINE_LENGTH < len(assignment):
                lines.extend((f"{prefix}(", f"        {code}", "    )"))
            else:
                lines.append(assignment)
    lines.extend(
        (
            "",
            "",
            "Dimensions = TypedDict(",
            '    "Dimensions",',
            "    {",
            *fields,
            "    },",
            "    total=False,",
            ")",
            "",
        )
    )
    temporary = None
    try:
        with NamedTemporaryFile(
            "w", encoding="utf-8", newline="\n", dir=output.parent, delete=False
        ) as stream:
            temporary = Path(stream.name)
            stream.write("\n".join(lines))
        temporary.replace(output)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main() -> None:
    parser = argparse.ArgumentParser(prog="pyivt")
    commands = parser.add_subparsers(dest="command", required=True)
    codegen = commands.add_parser("codegen", help="write Python types for one IVT file")
    codegen.add_argument("input", type=Path)
    codegen.add_argument("--output", type=Path, required=True)
    codegen.add_argument("--language", choices=("en", "fr"), default="en")
    args = parser.parse_args()
    try:
        _write_types(args.input, args.output, args.language)
    except (OSError, ValueError, MemoryError) as error:
        codegen.error(str(error))


if __name__ == "__main__":
    main()
