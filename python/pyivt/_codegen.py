"""Generate importable Python types for one IVT member map."""

from __future__ import annotations

import re
import unicodedata
from keyword import iskeyword
from os import PathLike
from pathlib import Path
from typing import BinaryIO

from pyivt._members import Language, Members
from pyivt._native import Ivt
from pyivt._native import open as open_ivt


def _words(label: str) -> list[str]:
    normalized = unicodedata.normalize("NFKD", label)
    text = "".join(c for c in normalized if not unicodedata.combining(c))
    return re.findall(r"[A-Za-z0-9]+", text)


def _unique(name: str, used: set[str]) -> str:
    candidate = name
    suffix = 2
    while candidate in used or iskeyword(candidate):
        candidate = f"{name}_{suffix}"
        suffix += 1
    used.add(candidate)
    return candidate


def codegen(
    source: Ivt
    | Members
    | str
    | PathLike[str]
    | bytes
    | bytearray
    | memoryview
    | BinaryIO,
    *,
    language: Language = "en",
) -> str:
    """Return Python module text from an IVT source or saved Members JSON.

    The module exports one IntEnum per axis, dimension and column names, and a
    typed selection() helper. Names use the requested member language for IVT
    sources and the saved labels for Members or JSON. No files are written.
    """
    if isinstance(source, Members):
        members = source
    elif isinstance(source, str) and source.lstrip().startswith("{"):
        members = Members.from_json(source)
    elif isinstance(source, (str, PathLike)) and Path(source).suffix.lower() == ".json":
        members = Members.read_json(Path(source))
    else:
        ivt = source if isinstance(source, Ivt) else open_ivt(source)
        members = ivt.members(language=language)

    slug_type = "Literal" if members.dimensions else "NoReturn"
    lines = [
        '"""Generated by pyivt.codegen."""',
        "",
        "from enum import IntEnum",
        f"from typing import {slug_type}, Sequence, TypedDict",
        "from pyivt import Selection",
        "",
        f"TABLE_ID = {members.table_id!r}",
        f"COLUMN_NAMES = {tuple(d.name for d in members.dimensions) + ('value',)!r}",
        "",
    ]
    used = {
        "IntEnum",
        "Literal",
        "NoReturn",
        "Sequence",
        "TypedDict",
        "Selection",
        "DimensionSlug",
        "SelectionCodes",
    }
    axes = []
    for dimension in members.dimensions:
        slug = dimension.name
        name = "".join(word.capitalize() for word in _words(slug)) or "Axis"
        if name[0].isdigit():
            name = "Axis" + name
        enum_name = _unique(name, used)
        axes.append((slug, enum_name))
        lines.extend(["", f"class {enum_name}(IntEnum):"])
        member_names: set[str] = set()
        if not dimension.members:
            lines.append("    pass")
        for member in dimension.members:
            name = "_".join(_words(member.label or "")).upper()
            if not name:
                name = f"CODE_{member.code}"
            elif name[0].isdigit():
                name = f"MEMBER_{name}"
            lines.append(f"    {_unique(name, member_names)} = {member.code}")

    slugs = ", ".join(repr(slug) for slug, _ in axes)
    if axes:
        lines.extend(["", "", f"DimensionSlug = Literal[{slugs}]"])
    else:
        lines.extend(["", "DimensionSlug = NoReturn"])
    lines.extend(["", 'SelectionCodes = TypedDict("SelectionCodes", {'])
    lines.extend(f"    {slug!r}: Sequence[{enum_name}]," for slug, enum_name in axes)
    lines.extend(
        [
            "}, total=False)",
            "",
            "",
            "def selection(codes: SelectionCodes) -> Selection:",
            "    unknown = codes.keys() - set(COLUMN_NAMES[:-1])",
            "    if unknown:",
            '        raise ValueError(f"unknown dimensions: {sorted(unknown)!r}")',
            "    selected: dict[str, Sequence[int]] = {}",
        ]
    )
    for slug, _ in axes:
        lines.extend(
            [
                f"    if {slug!r} in codes:",
                f"        selected[{slug!r}] = codes[{slug!r}]",
            ]
        )
    lines.extend(["    return Selection(selected)", ""])
    return "\n".join(lines)
